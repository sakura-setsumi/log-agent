let currentLanguage = defaultLanguage;

function languageFromStorage() {
  try {
    const saved = localStorage.getItem(languageStorageKey);
    if (supportedLanguages.includes(saved)) return saved;
  } catch (error) {
    // Storage unavailable: the default applies.
  }
  return defaultLanguage;
}

function activeLanguage() {
  return currentLanguage;
}

// t('key', { count: 3 }) fills {placeholders}. A missing translation falls back to
// Chinese (the source wording) and then to the key itself, so an untranslated
// string still renders something readable instead of an empty label.
function t(key, params = {}) {
  const table = i18n[currentLanguage] || {};
  const value = table[key] ?? i18n.zh[key] ?? key;
  return String(value).replace(/\{(\w+)\}/g, (match, name) => (params[name] ?? match));
}

// apiErrorMessage renders a backend failure in the UI language. Go answers
// with stable codes ("connect_failed") plus an optional technical "detail";
// anything that is not a known code is shown as-is when it reads like a
// sentence, or replaced by the caller's already-localized fallback otherwise.
function apiErrorMessage(source, fallback) {
  const raw = source ? String(source.error || source.message || '') : '';
  if (!raw) return fallback;
  const key = `api.${raw}`;
  if (t(key) !== key) return t(key, { detail: (source && source.detail) || '' });
  if (!/^[a-z0-9_]+$/.test(raw)) return raw;
  return fallback;
}

// applyI18n paints every keyed node under `root`. Re-running it after a language
// switch is enough for static markup, which is why the shell uses attributes
// instead of being rebuilt from templates.
function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  // `data-i18n-html` is for copy that carries its own inline markup (e.g. a
  // <code> path inside a sentence). Only ever fed from our own dictionary.
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-aria-label]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel)); });
  // `data-tooltip` drives the CSS tooltips, so it needs the same treatment.
  root.querySelectorAll('[data-i18n-tooltip]').forEach((el) => { el.dataset.tooltip = t(el.dataset.i18nTooltip); });
  document.documentElement.lang = currentLanguage === 'zh' ? 'zh-CN' : 'en';
  document.title = t('app.title');
}

function syncLanguageToggle() {
  const button = document.getElementById('language-toggle');
  if (!button) return;
  // Shows the language a click switches TO, matching the theme toggle's ☾/☀ habit.
  button.textContent = currentLanguage === 'en' ? '中' : 'EN';
  const label = t('topbar.language');
  button.title = label;
  button.setAttribute('aria-label', label);
}

function setLanguage(language) {
  if (!supportedLanguages.includes(language) || language === currentLanguage) return;
  currentLanguage = language;
  try {
    localStorage.setItem(languageStorageKey, language);
  } catch (error) {
    // The choice just does not survive a reload when storage is unavailable.
  }
  applyI18n();
  syncLanguageToggle();
  // Views assembled from templates carry their own copy, so they repaint.
  if (typeof onLanguageChanged === 'function') onLanguageChanged();
}

function toggleLanguage() {
  setLanguage(currentLanguage === 'en' ? 'zh' : 'en');
}

function initializeLanguage() {
  currentLanguage = languageFromStorage();
  applyI18n();
  syncLanguageToggle();
  document.getElementById('language-toggle')?.addEventListener('click', toggleLanguage);
}
